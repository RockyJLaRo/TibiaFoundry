def paths(rows, color_of):
    """One path per colour, made of the horizontal runs of that colour (compact and still pixel-exact)."""
    runs = {}
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == ch:
                x += 1
            runs.setdefault(ch, []).append(f"M{start} {y}h{x - start}v1h-{x - start}z")
    return [f'<path fill="{color_of(c)}" d="{"".join(d)}"/>' for c, d in runs.items()]


def grid(text):
    rows = [r for r in text.strip("\n").split("\n")]
    width = max(len(r) for r in rows)
    bad = [i for i, r in enumerate(rows) if len(r) != width]
    if bad:
        raise SystemExit(f"rows of different width: {bad}")
    return rows, width


def main():
    symbols = []
    for name, art in ICONS.items():
        rows, w = grid(art)
        if (w, len(rows)) != (16, 16):
            raise SystemExit(f"icon {name} is {w}x{len(rows)}, not 16x16")
        unknown = {c for r in rows for c in r} - set(PALETTE) - {"."}
        if unknown:
            raise SystemExit(f"icon {name}: unknown colours {unknown}")
        body = "".join(paths(rows, lambda c: f"var({PALETTE[c][0]},{PALETTE[c][1]})"))
        symbols.append(f'  <symbol id="px-{name}" viewBox="0 0 16 16">{body}</symbol>')
    out = os.path.join(SRC, "images", "pixel")
    os.makedirs(out, exist_ok=True)
    sprite = '<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">\n' + "\n".join(symbols) + "\n</svg>\n"
    # Since the stage-2 refinement the interface uses Lucide icons (art/icons.py). The pixel icons stay as an archive of
    # original artwork (art/pixel-icons.svg, not published); only the ornaments below are part of the site.
    open(os.path.join(HERE, "pixel-icons.svg"), "w", encoding="utf-8", newline="\n").write(sprite)
    for name, art in ORNAMENTS.items():
        rows, w = grid(art)
        body = "".join(paths(rows, lambda c: "#000"))
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {len(rows)}" width="{w}" height="{len(rows)}" '
               f'shape-rendering="crispEdges">{body}</svg>\n')
        open(os.path.join(out, f"{name}.svg"), "w", encoding="utf-8", newline="\n").write(svg)
    print(f"{len(ICONS)} icons -> art/pixel-icons.svg (archive); {len(ORNAMENTS)} ornaments -> src/images/pixel/")


if __name__ == "__main__":
    main()
