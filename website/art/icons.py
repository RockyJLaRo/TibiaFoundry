"""The website's interface icons: a subset of Lucide (https://lucide.dev, ISC licence, see art/lucide/LICENSE), version 0.460.0.

    python -I website/art/icons.py          (writes website/src/ui-icons.svg)

art/lucide/<name>.svg are unmodified copies of lucide-static@0.460.0/icons/<name>.svg. This script turns them into one
inline sprite of <symbol id="i-<name>"> elements that the layout includes once per page (no request, no dependency).
Use: <svg class="ic" aria-hidden="true"><use href="#i-download"/></svg>. Stroke colour follows the text colour
(currentColor); the stroke width comes from --icon-stroke (default 2, the Lucide standard) so every icon has the same
weight at 16-24 px.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")
VERSION = "0.460.0"

# Each icon and what it means on the site (an icon is only used for this meaning).
ICONS = {
    "menu": "open the menu", "x": "close", "search": "search", "sun": "switch to light", "moon": "switch to dark",
    "languages": "language", "download": "download", "external-link": "opens another website", "arrow-up-down": "column can be sorted",
    "arrow-up": "sorted ascending", "arrow-down": "sorted descending", "info": "explanation", "triangle-alert": "warning",
    "circle-check": "success", "circle-x": "error", "copy": "copy", "check": "copied / included", "refresh-cw": "reload",
    "chevron-right": "next level / more", "chevron-down": "expands", "mail": "email", "shield-check": "safety notice / legal",
    "file-archive": "ZIP package", "code-xml": "source code", "monitor": "desktop app", "book-open": "guides", "scroll-text": "legal text",
    "list-filter": "filter", "arrow-left": "previous page", "arrow-right": "next page", "user": "character", "users": "guild",
    "globe": "world", "trophy": "highscores", "house": "houses", "skull": "kill statistics", "paw-print": "creatures",
    "crown": "bosses", "wand-sparkles": "spells", "newspaper": "news", "archive": "news archive", "flag": "fansites",
    "anvil": "Tibia Foundry (the foundry)", "gem": "boosted", "calendar": "date", "map-pin": "location", "coins": "price",
    "user-round": "creator / contact person", "package": "installer",
}


def main():
    symbols = []
    for name in ICONS:
        text = open(os.path.join(HERE, "lucide", name + ".svg"), encoding="utf-8").read()
        inner = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
        inner = re.sub(r"\s+", " ", inner).replace(" />", "/>").replace("> <", "><").strip()
        symbols.append(f'  <symbol id="i-{name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" '
                       f'style="stroke-width:var(--icon-stroke,2)" stroke-linecap="round" stroke-linejoin="round">{inner}</g></symbol>')
    out = (f"<!-- Lucide {VERSION} (ISC licence, https://lucide.dev) – generated by website/art/icons.py -->\n"
           '<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">\n'
           + "\n".join(symbols) + "\n</svg>\n")
    open(os.path.join(SRC, "ui-icons.svg"), "w", encoding="utf-8", newline="\n").write(out)
    print(f"{len(symbols)} icons -> src/ui-icons.svg ({len(out):,} bytes)")


if __name__ == "__main__":
    main()
