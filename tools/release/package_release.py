"""
Packages a published release into dist/ (run from the repository root after both publishes):
  python -I tools/release/package_release.py
Writes THIRD-PARTY-NOTICES.txt (via make_notices.py, from the folder edition's deps.json), copies it and
README-Portable.txt next to the programs, zips both editions and the source, and writes SHA256SUMS.txt.
"""
import hashlib
import os
import re
import subprocess
import sys
import zipfile

root = os.getcwd()
version = re.search(r"<Version>([^<]+)</Version>", open(os.path.join(root, "src", "Directory.Build.props"), encoding="utf-8").read()).group(1)
dist = os.path.join(root, "dist")
folder = os.path.join(dist, f"TibiaFoundry-{version}-win-x64")
portable = os.path.join(dist, f"TibiaFoundry-{version}-portable-win-x64")
for d in (folder, portable):
    if not os.path.isfile(os.path.join(d, "TibiaFoundry.exe")):
        sys.exit(f"Not published: {d}")
# The portable edition is one file: TagLib# and every other library are bundled into it.
extra = [f for f in os.listdir(portable) if f.lower().endswith(".dll")]
if extra:
    sys.exit("The portable edition must be a single file; found: " + ", ".join(extra))

notices = os.path.join(root, "THIRD-PARTY-NOTICES.txt")
subprocess.run([sys.executable, "-I", os.path.join(root, "tools", "release", "make_notices.py"), "src", notices, os.path.join(folder, "TibiaFoundry.deps.json")], check=True)
for d in (folder, portable):
    open(os.path.join(d, "THIRD-PARTY-NOTICES.txt"), "wb").write(open(notices, "rb").read())
open(os.path.join(portable, "README-Portable.txt"), "wb").write(open(os.path.join(root, "tools", "release", "README-Portable.txt"), "rb").read())


def zip_dir(src, target, prefix=""):
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for base, dirs, files in os.walk(src):
            dirs[:] = sorted(d for d in dirs if d != "TibiaFoundry-Data")
            for f in sorted(files):
                full = os.path.join(base, f)
                z.write(full, os.path.join(prefix, os.path.relpath(full, src)).replace("\\", "/"))


zips = [os.path.join(dist, f"TibiaFoundry-{version}-portable-win-x64.zip"), os.path.join(dist, f"TibiaFoundry-{version}-win-x64.zip")]
zip_dir(portable, zips[0])
zip_dir(folder, zips[1])

# Source: everything except build outputs, the release folder and editor state.
skip = {"bin", "obj", "dist", ".vs", "__pycache__", "Release_Artifacts", ".git", "TestResults", "BenchmarkDotNet.Artifacts",
        # Never part of Tibia Foundry (other projects that share the website repository).
        "pokemon", "games"}
skip_files = {".user", ".suo", ".log"}
source = os.path.join(dist, f"TibiaFoundry-{version}-source.zip")
with zipfile.ZipFile(source, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for base, dirs, files in os.walk(root):
        # The top-level "Release" folder holds the finished packages of each version (8.8.1), never source.
        dirs[:] = sorted(d for d in dirs if d not in skip and not d.startswith("Release_Artifacts") and not (base == root and d == "Release")
                         # 9.0: the built website (website/site) is generated by website/build_site.py from website/src.
                         and not (os.path.normcase(base) == os.path.normcase(os.path.join(root, "website")) and d == "site"))
        for f in sorted(files):
            # 9.0.4: in a git worktree ".git" is a file that names the local repository folder; it is never source.
            if f == ".git" or os.path.splitext(f)[1].lower() in skip_files:
                continue
            full = os.path.join(base, f)
            z.write(full, os.path.join(f"TibiaFoundry-{version}-source", os.path.relpath(full, root)).replace("\\", "/"))
zips.append(source)

lines = []
for path in zips:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    lines.append(f"{h.hexdigest()}  {os.path.basename(path)}")
    print(f"{os.path.basename(path)}: {os.path.getsize(path) / 1e6:.1f} MB")
open(os.path.join(dist, "SHA256SUMS.txt"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("\n".join(lines))
