def run(args):
    return subprocess.run(args, cwd=src, capture_output=True, text=True, encoding="utf-8", errors="replace")

lines = []
only = set(sys.argv[3:])  # optional: run only these IDs
for aid, what, rel, old, new, flt, *more in M:
    if only and aid not in only:
        continue
    path = os.path.join(src, rel)
    original_bytes = open(path, "rb").read()
    original = open(path, encoding="utf-8").read()
    # Optional second replacement in the same file (for safeguards that exist twice).
    pairs = [(old, new)] + ([(more[0], more[1])] if more else [])
    if any(original.count(o) != 1 for o, _ in pairs):
        lines.append(f"{aid}: SNIPPET NOT FOUND ({rel})"); print(lines[-1], flush=True); continue
    try:
        mutated = original
        for o, n in pairs:
            mutated = mutated.replace(o, n)
        open(path, "w", encoding="utf-8").write(mutated)
        b = run(["dotnet", "build", "TibiaFoundry.Tests/TibiaFoundry.Tests.csproj", "-c", "Debug", "-v", "q", "-nologo"])
        if b.returncode != 0:
            lines.append(f"{aid}: mutant did not compile"); print(lines[-1], flush=True); continue
        t = run(["dotnet", "test", "TibiaFoundry.Tests/TibiaFoundry.Tests.csproj", "-c", "Debug", "--nologo", "--no-build", "--filter", flt])
        summary = [l.strip() for l in t.stdout.splitlines() if "Total:" in l]
        failed = [l.strip() for l in t.stdout.splitlines() if "[FAIL]" in l]
        verdict = "DETECTED" if t.returncode != 0 and any("Failed!" in l for l in summary) else "NOT DETECTED"
        lines.append(f"{aid} ({what}): {verdict} - {summary[-1] if summary else t.stdout[-300:]} " + "; ".join(f.split('.')[-1] for f in failed))
    finally:
        open(path, "wb").write(original_bytes)
    print(lines[-1], flush=True)

b = run(["dotnet", "build", "TibiaFoundry.Tests/TibiaFoundry.Tests.csproj", "-c", "Debug", "-v", "q", "-nologo"])
lines.append("restored build: " + ("ok" if b.returncode == 0 else "FAILED"))
open(report, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(lines[-1])
